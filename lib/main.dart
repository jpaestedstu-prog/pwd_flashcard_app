SystemUiOverlayStyle _systemUiStyleFor({required bool isDark}) {
  final iconBrightness = isDark ? Brightness.light : Brightness.dark;
  return SystemUiOverlayStyle(
    statusBarColor: Colors.transparent,
    statusBarIconBrightness: iconBrightness,
    statusBarBrightness: isDark ? Brightness.dark : Brightness.light,
    systemNavigationBarColor: Colors.transparent,
    systemNavigationBarIconBrightness: iconBrightness,
    systemNavigationBarDividerColor: Colors.transparent,
    systemNavigationBarContrastEnforced: false,
    systemStatusBarContrastEnforced: false,
  );
}

void main() {
  // Wrap the entire startup in a guarded zone so that
  // ensureInitialized() and runApp() share the SAME zone.
  // This prevents the "Zone mismatch" error.
  ErrorHandler.runGuarded(() async {
    WidgetsFlutterBinding.ensureInitialized();

    // Install global error handling FIRST
    ErrorHandler.init();
    setupErrorWidget();

    // ─── High Refresh-Rate Performance Configuration ──────
    // Flutter 3.x automatically targets the display's native refresh rate
    // (120 Hz on Honor Pad X8a) so no manual configuration is needed.

    // Pointer-event resampling stays OFF (Flutter's default). When enabled,
    // touch events are queued and replayed against the frame clock; on
    // tablets whose input timestamps drift from that clock (or when a frame
    // janks) the queue flushes late, so single taps feel dead and users end
    // up tapping repeatedly. Direct dispatch keeps every tap immediate.
    GestureBinding.instance.resamplingEnabled = false;

    // Increase decoded image cache for a 4 GB device with heavy flashcard
    // images. Default is 100 MB; we raise to 256 MB so scrolling large
    // grids doesn't repeatedly decode the same assets.
    PaintingBinding.instance.imageCache.maximumSizeBytes = 256 << 20; // 256 MB
    PaintingBinding.instance.imageCache.maximumSize = 200; // up to 200 images

    // Prevent Google Fonts from making HTTP requests at runtime.
    // Fonts are bundled in the google_fonts/ directory instead.
    // This avoids ANR on devices with slow or no internet.
    GoogleFonts.config.allowRuntimeFetching = false;

    // Orientation: portrait-only on every device — phones AND tablets.
    // The layouts, the Gaze Control D-pad grid, and the front-camera head/
    // blink geometry are all authored against a fixed portrait frame, so a
    // consistent orientation is what keeps spatial navigation predictable
    // for PWD learners. The AndroidManifest also pins the activity to
    // `portrait` so there is no landscape flash before this runtime call
    // (which overrides the manifest) takes effect. portraitDown is included
    // so a 180° flip keeps content upright without ever entering landscape.
    await SystemChrome.setPreferredOrientations(const [
      DeviceOrientation.portraitUp,
      DeviceOrientation.portraitDown,
    ]);

    // Edge-to-edge: draw under status + nav bars. Android 15 (targetSdk
    // 35+) enforces this anyway; setting it explicitly gives consistent
    // behavior on Android 10+. We can't await this on older versions
    // where it's a no-op, so fire-and-forget.
    await SystemChrome.setEnabledSystemUIMode(SystemUiMode.edgeToEdge);

    // Transparent system bars at startup. Per-theme icon brightness is
    // re-applied inside [FlashLearnApp.build] once we know the theme.
    SystemChrome.setSystemUIOverlayStyle(_systemUiStyleFor(isDark: false));

    // Initialize Hive, Firebase, and Notifications in parallel
    // (they are independent of each other)
    await Future.wait([
      HiveService.init(),
      // Parse the media manifests (real photos + "Show Me" action clips) so
      // FlashcardImage / the Picture-Word game / the viewer know what's
      // available by first render. Both swallow errors and stay dormant when
      // no manifest URL is configured, so this never blocks or breaks startup.
      FlashcardPhotoService.load(),
      ActionClipService.load(),
      FirebaseService.init(options: DefaultFirebaseOptions.currentPlatform),
      NotificationService.init(
        onNotificationTap: (payload) {
          WidgetsBinding.instance.addPostFrameCallback((_) {
            final ctx = rootNavigatorKey.currentContext;
            if (ctx == null) return;
            switch (payload) {
              case 'daily_challenge':
                GoRouter.of(ctx).go('/home');
              case 'vocab_review':
                GoRouter.of(ctx).go('/smart-review');
              default:
                GoRouter.of(ctx).go('/home');
            }
          });
        },
      ),
    ]);

    // Open the error logs box (after Hive.init)
    await Hive.openBox('error_logs');

    // Migrate any plaintext PINs to salted PBKDF2 hashes before the first
    // PIN-gated screen can be reached. Local-only and idempotent — a
    // settings flag and per-profile guards prevent double-hashing.
    await PinMigration.runIfNeeded();

    // Build the sync plumbing now — constructors are I/O-free and the
    // provider overrides below need the instances synchronously. The
    // network side (listeners, queue drain) starts in the background
    // chain after sign-in.
    SyncService? syncInstance;
    SyncQueueService? queueInstance;
    ProgressSyncListener? progressListener;
    ProfileSyncListener? profileListener;
    if (FirebaseService.isConfigured) {
      syncInstance = SyncService(
        local: const LocalRepository(),
        remote: const FirestoreRepository(),
      );
      queueInstance = syncInstance.queueService;

      // Bidirectional sync: subscribe to remote progress for every
      // profile on this device so updates from other devices land in
      // Hive and refresh the UI without a manual reload.
      progressListener = ProgressSyncListener();

      // Mirror listener for `profiles/{id}` — picks up educator-driven
      // name patches (Manage Classes > Rename, Home Group > Rename) so
      // the learner's own device shows the new name without a relaunch.
      profileListener = ProfileSyncListener();
    }

    // Everything that may touch the network runs AFTER the first frame,
    // behind the splash screen, so a slow or absent connection can never
    // hold the app on the native splash. Order inside the chain matters:
    // sign-in mints the auth uid that the migrations stamp onto local
    // data and that Firestore security rules require for the listeners.
    final sync = syncInstance;
    final queue = queueInstance;
    final progressSync = progressListener;
    final profileSync = profileListener;
    unawaited(() async {
      try {
        // Anonymous auth so every Firestore write carries an auth uid.
        await FirebaseService.signInAnonymously();

        // Opt-in telemetry (Crashlytics + Analytics). Reads the persisted
        // opt-in flag from Hive — default OFF, so nothing is sent until an
        // educator opts in via Settings → "Help improve the app".
        await AnalyticsService.initialize();

        // Claim ownership of pre-auth profiles for this device's uid.
        // Skips without setting its done-flag when sign-in didn't
        // complete, so it retries on the next boot.
        await OwnerUidMigration.runIfNeeded();

        // Mint a messaging handle for every legacy profile that doesn't
        // have one yet. Idempotent (flag + per-profile null check).
        await UsernameMigration.runIfNeeded();

        // With auth in place, open the sync pipes: connectivity listener,
        // pending-write drain, and the remote progress/profile mirrors.
        sync?.startListening();
        queue?.processQueue();
        progressSync?.start();
        profileSync?.start();
      } catch (e, s) {
        // Background startup must never pop the global error snackbar —
        // every step retries on the next boot or on demand (ensureSignedIn).
        ErrorHandler.report(e, s, 'startupBackground:silent');
      }
    }());

    runApp(
      ProviderScope(
        overrides: [
          if (syncInstance != null)
            syncServiceProvider.overrideWithValue(syncInstance),
          if (queueInstance != null)
            syncQueueServiceProvider.overrideWithValue(queueInstance),
          if (progressListener != null)
            progressSyncListenerProvider.overrideWithValue(progressListener),
          if (profileListener != null)
            profileSyncListenerProvider.overrideWithValue(profileListener),
        ],
        child: const FlashLearnApp(),
      ),
    );
  });
}

class FlashLearnApp extends ConsumerWidget {
  const FlashLearnApp({super.key});

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final router = ref.watch(routerProvider);
    final settings = ref.watch(settingsProvider);

    // ── Active-time tracking + alarm scheduler lifecycle ──
    // When the active profile is a student/child, start the tracker
    // and the alarm scheduler. Otherwise (teacher/parent/no profile),
    // stop the tracker so a teacher previewing a student dashboard
    // doesn't spuriously rack up "minutes used today" against their
    // own profile — but leave the last learner's alarms scheduled (see
    // [ScheduleOwnership]).
    //
    // The whole body is wrapped in try/catch so that a plugin-init or
    // tracker hiccup at the moment a learner becomes active does not
    // surface as the global "Something went wrong" snackbar — that was
    // the user-facing artefact reported after a successful join. The
    // error is still persisted to the Hive diagnostics log via
    // [ErrorHandler.report] under the silent source 'applyLifecycle:silent'.
    void applyLifecycle(UserProfile? active) {
      try {
        // "View as student" is still the educator at the tablet: the learner
        // whose dashboard is open did not sign in (see [profileAtTablet]).
        final next =
            profileAtTablet(active, ref.read(profileProvider.notifier));
        final alarmOwner = AlarmScheduler.scheduledFor;
        final alarmChange = ScheduleOwnership.forAlarms(
          next,
          owner: alarmOwner,
          responsibleEducators:
              AlarmScheduler.responsibleEducatorsFor(alarmOwner),
        );
        if (next != null && alarmChange == ScheduleChange.start) {
          // Wire alarm tap → "Time's Up" lock screen for `lockScreen`
          // actions; for `endSession`, just route home; `notifyOnly`
          // does nothing extra.
          AlarmScheduler.onAlarmFired = (alarm) {
            if (alarm == null) return;
            final ctx = rootNavigatorKey.currentContext;
            if (ctx == null) return;
            try {
              switch (alarm.action) {
                case AlarmAction.lockScreen:
                  GoRouter.of(ctx).go('/time-up-lock');
                case AlarmAction.endSession:
                  GoRouter.of(ctx).go('/home');
                case AlarmAction.notifyOnly:
                  break;
              }
            } catch (e, s) {
              // GoRouter can throw if the navigator is being rebuilt or
              // the alarm fires during a route transition. Log silently
              // so the user doesn't see a generic snackbar — the
              // wall-clock ticker in `lockStateProvider` will surface
              // the lock again within 10 s if it should still apply.
              ErrorHandler.report(e, s, 'OnAlarmFired:silent');
            }
          };
          ActiveTimeTracker.start(next.id);
          // Init returns a Future; failures inside the plugin init or
          // the first reschedule must not escape into the zone, or the
          // global error boundary fires its generic snackbar right
          // after a successful join. Catch + report under a silent source.
          unawaited(
            AlarmScheduler.init(next.id).catchError((e, s) {
              ErrorHandler.report(e, s, 'AlarmScheduler:silent');
            }),
          );

        } else {
          // The alarms stay. They belong to the last learner on this device,
          // and shutting them down here cancelled a child's 1:20 PM alarm the
          // moment an educator — or just the profile picker — opened. Another
          // learner signing in replaces them; deleting the learner cancels
          // them (LocalRepository.deleteProfile). Somebody else using a
          // shared tablet — an unrelated educator or a Player — holds them
          // back until they leave, so a child's alarm never pops up in their
          // session.
          AlarmScheduler.onAlarmFired = null;
          ActiveTimeTracker.stopActive();
          unawaited(
            (alarmChange == ScheduleChange.suspend
                    ? AlarmScheduler.suspend()
                    : AlarmScheduler.resume())
                .catchError((Object e, StackTrace s) {
              ErrorHandler.report(e, s, 'AlarmScheduler:silent');
            }),
          );
        }
      } catch (e, s) {
        ErrorHandler.report(e, s, 'applyLifecycle:silent');
      }
    }

    // ── Routine reminders ──
    // Its own lifecycle, not part of [applyLifecycle], for two reasons: it
    // runs for Players as well as Students and Children (a Player's My Day is
    // a checklist, but a checklist nobody is nudged toward is a checklist that
    // gets forgotten), and a Player can switch it off mid-session, which the
    // profile listener alone would never notice.
    void applyRoutineLifecycle() {
      try {
        // An educator peeking at a learner's dashboard changes nobody's
        // reminders.
        if (ref.read(profileProvider.notifier).isViewingAsStudent) return;
        final next = ref.read(profileProvider);
        final routineOwner = RoutineReminderScheduler.profileId;
        final change = ScheduleOwnership.forRoutines(
          next: next,
          featureOn: ref.read(routineFeatureProvider),
          scheduledFor: routineOwner,
          responsibleEducators:
              AlarmScheduler.responsibleEducatorsFor(routineOwner),
        );
        if (next != null && change == ScheduleChange.start) {
          RoutineReminderScheduler.onReminderTapped = (routineId, stepId) {
            final ctx = rootNavigatorKey.currentContext;
            if (ctx == null) return;
            try {
              // The notification and the in-app pop-up say the same
              // thing at the same minute, so a tapped notification lands the
              // learner *in* the pop-up (the watcher in the learner shell
              // sees the request and raises it) rather than leaving them to
              // find the step. They tapped "Please have your lunch now" —
              // making them hunt for it would undo the tap.
              //
              // A step that is holding the device right now goes
              // straight to its lock. The pop-up is deliberately NOT armed
              // for it: the interstitial offers "Later", and offering
              // "Later" for a step the app will not let the learner past is
              // a promise the very next screen breaks.
              final locked = ref.read(lockStateProvider(next.id));
              if (locked is RoutineStepDue && locked.step.id == stepId) {
                ref.read(pendingRoutinePopupProvider.notifier).state = null;
                GoRouter.of(ctx).go('/routine-lock');
                return;
              }
              // A check-in opens on Home, because it is a question rather
              // than a chore; any other step opens on "My Day", so the rest
              // of the day is visible behind its pop-up. `/routine` takes no
              // path parameter on purpose — a learner must never reach
              // another learner's day.
              final isCheckIn = ref
                  .read(todayRoutineProvider)
                  .steps
                  .any((s) => s.id == stepId && s.activity.isMoodCheckIn);
              ref.read(pendingRoutinePopupProvider.notifier).state = stepId;
              GoRouter.of(ctx).go(isCheckIn ? '/home' : '/routine');
            } catch (e, s) {
              ErrorHandler.report(e, s, 'OnRoutineReminder:silent');
            }
          };
          unawaited(
            RoutineReminderScheduler.init(
              next.id,
              accessibility: next.disabilityType,
              filipino: ref.read(settingsProvider).locale == 'fil',
            ).catchError((e, s) {
              ErrorHandler.report(e, s, 'RoutineReminderScheduler:silent');
            }),
          );
        } else {
          RoutineReminderScheduler.onReminderTapped = null;
          // Only the profile the reminders are for can switch them off. The
          // educator who set the routine and the profile picker leave them
          // running; anyone else on a shared tablet holds them back while
          // they use the app.
          final pending = switch (change) {
            ScheduleChange.stop => RoutineReminderScheduler.shutdown(),
            ScheduleChange.suspend => RoutineReminderScheduler.suspend(),
            _ => RoutineReminderScheduler.resume(),
          };
          unawaited(pending.catchError((Object e, StackTrace s) {
            ErrorHandler.report(e, s, 'RoutineReminderScheduler:silent');
          }));
        }
      } catch (e, s) {
        ErrorHandler.report(e, s, 'applyRoutineLifecycle:silent');
      }
    }

    // Apply once for the current values, then react to subsequent changes.
    applyLifecycle(ref.read(profileProvider));
    applyRoutineLifecycle();
    ref.listen(profileProvider, (_, next) {
      applyLifecycle(next);
      applyRoutineLifecycle();
      // A Teacher's or Parent's start/end alerts are theirs: once a learner
      // (or nobody) is signed in on this device they must not keep arriving.
      // The dashboard re-plans them when an educator is back. Viewing a
      // learner's dashboard keeps them: the educator is still at the tablet.
      final atTablet =
          profileAtTablet(next, ref.read(profileProvider.notifier));
      if (atTablet == null || !atTablet.role.isEducator) {
        unawaited(RoutineReminderScheduler.cancelEducatorAlerts());
      }
    });
    // A Player turning My Day off has to cancel the pending notifications it
    // already scheduled, or the feature they switched off keeps tapping them
    // on the shoulder every morning.
    ref.listen(routineFeatureProvider, (_, _) => applyRoutineLifecycle());
    // Midnight with the app running. The ticker (already alive for the lock)
    // notices the date change; moving [currentDayProvider] rebuilds "My Day"
    // and its history for the new day, and the reminder scheduler follows the
    // new day's log and actions (see RoutineReminderScheduler.onDayChanged).
    ref.listen<AsyncValue<DateTime>>(wallClockTickerProvider, (_, next) {
      final now = next.valueOrNull;
      if (now != null && isNewDay(ref.read(currentDayProvider), now)) {
        ref.invalidate(currentDayProvider);
      }
    });
    ref.listen<DateTime>(
      currentDayProvider,
      (_, _) => unawaited(RoutineReminderScheduler.onDayChanged()),
    );

    // Session logging. This `watch` is the whole point of the line: a Riverpod
    // `Provider` is lazy, so until something reads it the tracker is never
    // constructed, never registers its lifecycle observer and never writes a
    // row. It had no readers at all, which is why every surface that reports
    // study time — the Progress week panel, Detailed Analytics, the streak
    // calendar, the teacher dashboard and the research export — showed zero
    // minutes and zero sessions for the life of the app.
    //
    // Watched here rather than inside a learner-only branch because session
    // rows are per *profile*, not per role; an educator's own sittings belong
    // in the export too. Rebuilding on profile change is intended: the old
    // tracker is disposed (writing its final row) and a new one starts.
    ref.watch(sessionTrackerProvider);

    // Check for equipped shop theme (acc essibility themes take priority)
    // Watch progress state to rebuild on changes, then read equipped item
    ref.watch(progressProvider);
    final equippedThemeId = ref
        .read(progressProvider.notifier)
        .getEquippedItemId(ShopItemType.theme);

    // Active profile drives the per-profile themes below; watch so the app
    // re-themes when the user switches profiles.
    final profileForTheme = ref.watch(profileProvider);
    final roleForTheme = profileForTheme?.role;
    // Accessibility-profile palette applies to Students (Classroom) and
    // Children (Family Group); educators and players fall through.
    final isThemedLearner =
        roleForTheme == UserRole.student || roleForTheme == UserRole.child;
    final accessTypeForTheme = isThemedLearner
        ? profileForTheme?.disabilityType
        : null;

    // Choose theme based on settings — accessibility first, then shop theme,
    // then the learner's accessibility-profile palette, then the group theme
    // (Classroom blue / Family coral for educators).
    // Cascade order: high-contrast (per-profile accent) > dyslexia >
    // (dark mode × shop theme) > (dark mode × learner palette) > dark mode >
    // shop theme > learner palette > group theme > light. The dark-mode ×
    // shop-theme combo matters because users who paid for a shop theme expect
    // their palette to follow them into night mode instead of being kicked to
    // stock dark. Learner/group themes sit at the bottom so accessibility
    // modes and a purchased shop theme always win.
    final ThemeData baseTheme;
    if (settings.highContrastMode) {
      baseTheme = AppTheme.highContrastFor(accessTypeForTheme);
    } else if (settings.dyslexiaMode) {
      baseTheme = AppTheme.dyslexia;
    } else if (settings.darkMode) {
      baseTheme =
          AppTheme.shopThemeDark(equippedThemeId) ??
          AppTheme.learnerThemeDark(accessTypeForTheme) ??
          AppTheme.dark;
    } else {
      baseTheme =
          AppTheme.shopTheme(equippedThemeId) ??
          AppTheme.learnerTheme(accessTypeForTheme, roleForTheme) ??
          AppTheme.groupTheme(roleForTheme) ??
          AppTheme.light;
    }

    // Adjust both status bar AND nav bar icons for dark themes. The
    // nav bar piece matters under edge-to-edge — without it, light icons
    // on a light Flutter background go invisible after a theme toggle.
    SystemChrome.setSystemUIOverlayStyle(
      _systemUiStyleFor(isDark: baseTheme.brightness == Brightness.dark),
    );

    // Reduced-motion contract: when on, strip page-route transitions too
    // so navigation is instant (Animate.defaultDuration already covers
    // in-screen flutter_animate calls).
    final theme = settings.reducedMotion
        ? AppTheme.withReducedMotion(baseTheme)
        : baseTheme;

    // When reduced motion is enabled, set all flutter_animate durations to zero
    // so every .animate() call throughout the app becomes instant.
    // When reduced motion is enabled, skip all flutter_animate durations.
    // Otherwise use a snappy 250 ms default (lower than 300 ms for 120 Hz feel).
    Animate.defaultDuration = settings.reducedMotion
        ? Duration.zero
        : const Duration(milliseconds: 250);

    // The global above only reaches animations that read their duration from
    // it — one-shots. Endless `repeat()` loops have to be started and stopped,
    // and the widgets holding them need to hear about the toggle to do it. The
    // scope goes *outside* MaterialApp so the overlays built in `builder`
    // below (achievement, coach marks, connectivity) are covered too.
    return ReducedMotionScope(
      reduced: settings.reducedMotion,
      child: MaterialApp.router(
        title: 'FlashLearn PWD',
        debugShowCheckedModeBanner: false,
        theme: theme,
        routerConfig: router,
        locale: Locale(settings.locale),
        supportedLocales: AppLocalizations.supportedLocales,
        localizationsDelegates: AppLocalizations.localizationsDelegates,
        builder: (context, child) {
          // Apply global font scale from settings, multiplied against the
          // OS scale, then clamp the product into a layout-safe range so
          // extreme system font scales (some Android skins go to 2.0) don't
          // overflow game/flashcard tiles.
          final mediaQuery = MediaQuery.of(context);
          final systemScale = mediaQuery.textScaler.scale(1.0);
          final combined = (systemScale * settings.fontScale).clamp(0.85, 1.5);
          return MediaQuery(
            data: mediaQuery.copyWith(textScaler: TextScaler.linear(combined)),
            // ErrorBoundary (global error snackbars), ConnectivityBanner (offline
            // indicator), then MembershipEvictionGate above LockEnforcerGate so an
            // educator-driven removal wins over a time-driven lock.
            // LockWarningGate sits just *inside* LockEnforcerGate: its "nearly
            // time" banner belongs over normal learner screens but never over a
            // lock or eviction screen.
            // CompanionHost sits *inside* the lock / eviction gates so the
            // floating AI Companion never shows over a lock or eviction screen,
            // but floats above every normal learner screen.
            // CastStatusHost sits alongside it, for the mirror-image reason: the
            // TV Cast server outlives the cast screen, so the "still casting"
            // pill has to be able to float over any educator surface — but never
            // over a lock or eviction screen.
            // GamepadHost shares that placement, for a third reason: it drives
            // navigation from a Bluetooth controller, and a lock screen is meant
            // to be a dead end. Inside the gates, a locked-out learner cannot
            // steer their way past it; the controller comes back the moment the
            // lock lifts. Above the router, though, so it keeps working across
            // every pushed screen, game and dialog.
            child: ErrorBoundary(
              child: ConnectivityBanner(
                child: MembershipEvictionGate(
                  child: LockEnforcerGate(
                    child: LockWarningGate(
                      child: GamepadHost(
                        child: CompanionHost(
                          child: CastStatusHost(
                            child: child ?? const SizedBox.shrink(),
                          ),
                        ),
                      ),
                    ),
                  ),
                ),
              ),
            ),
          );
        },
      ),
    );
  }
}

// Scroll behavior intentionally stays at the MaterialScrollBehavior default.
